/// \class TRestDetectorChargeResponse
/// \brief Charge response of a medium: ionisation (W-value, Fano factor), transport of the charge carriers
/// versus the field and avalanche gain, from the tables of the medium file (TRestDetectorTransportTable,
/// TRestDetectorGainTable, generated by restGarfield) at the pressure and temperature of the medium, or
/// fixed transport parameters without tables.
///
/// It is the `charge` key of a TRestDetectorMedium (no class key), which creates it and gives it its file
/// and conditions; the processes ask the medium for it (TRestDetectorMedium::GetChargeResponse) and it for
/// the parameters at the drift field (e.g. charge.GetDriftVelocity()) or at a given field.
///
/// Parameters:
/// - wValue: mean energy to create an ionisation electron (e.g. 26.2 eV); fanoFactor (0).
/// - driftField: the drift field of the detector (e.g. 140 V/cm), where the transport tables are evaluated
///   for the drift processes; needed with transport tables. Two drift regions are two media.
/// - driftVelocity, longDiff, transDiff (sqrt(cm)), attachment (1/cm): fixed electron transport, used
///   when there are no transport tables (e.g. no mediumFile), for any field. With transport tables they
///   are written with the values of the tables at driftField (those used by the drift processes, kept
///   in the stored metadata); the tables still give them at any field.
/// - transportTable: key of the transport table to use (all the tables at the conditions if empty).
/// - loadedTables: written with the keys of the tables loaded (not an input).
///
/// Transport tables: all those at the pressure and temperature of the medium or else, for gases, those at
/// the closest pressure scaled with E/p. For a field, the narrowest table whose range contains it; out of
/// all of them, the closest one (constant out of its range), with a warning the first time. Amplification
/// tables: those at the pressure and temperature (the gain does not scale with the pressure), chosen by gap
/// and key (GetGainTable).
///
///    medium:
///      class: "TRestDetectorMedium"
///      name: "ArIso"
///      mediumFile: "ArIso.root"
///      pressure: 1 bar
///      charge:
///        wValue: 26.2 eV
///        fanoFactor: 0.2
///        driftField: 140 V/cm
class TRestDetectorChargeResponse : public TRestMetadata {
   private:
    std::vector<std::shared_ptr<const TRestDetectorTransportTable>> fTransportTables;  //!
    std::vector<std::shared_ptr<const TRestDetectorGainTable>> fGainTables;            //!
    /// Warning of a field out of the transport tables already given (shared by the copies)
    std::shared_ptr<std::atomic<bool>> fRangeWarned = std::make_shared<std::atomic<bool>>(false);  //!
    /// Name and conditions of the medium
    std::string fMediumName = "";  //!
    double fPressure = 1;          //!
    double fTemperature = 293.15;  //!

    void LoadTables(TFile* file);
    void CheckCarrier(const std::string& carrier) const;
    /// Drift field (V/mm); throws if there are transport tables and no driftField
    double GetDriftFieldForTables() const;

   public:
    TRestWithUnits fWValue = 0;         ///< `wValue`: mean energy per ionisation electron
    double fFanoFactor = 0;             ///< `fanoFactor`
    TRestWithUnits fDriftField = 0;     ///< `driftField`: drift field of the detector (V/mm)
    TRestWithUnits fDriftVelocity = 0;  ///< `driftVelocity`: fixed drift velocity (mm/us), without tables
    double fLongitudinalDiffusion = 0;  ///< `longDiff`: fixed longitudinal diffusion (sqrt(cm))
    double fTransversalDiffusion = 0;   ///< `transDiff`: fixed transversal diffusion (sqrt(cm))
    double fAttachment = 0;             ///< `attachment`: fixed attachment coefficient (1/cm)
    std::string fTransportTable = "";   ///< `transportTable`: key of the transport table to use
    std::vector<std::string> fLoadedTables;  ///< `loadedTables`: keys of the tables loaded (output)

    /// \brief Builds an empty charge response.
    TRestDetectorChargeResponse();
    /// \brief Builds the response from the `charge` node of a medium (LoadConfig); the tables are loaded
    /// by SetMedium.
    TRestDetectorChargeResponse(const std::string& instanceName, const YAML::Node& node);
    ~TRestDetectorChargeResponse() override;

    /// \brief Returns the class name, "TRestDetectorChargeResponse".
    std::string GetClassName() const override { return "TRestDetectorChargeResponse"; }
    /// \brief Reads the parameters; throws if one of them is negative or endReflectivity is above 1.
    void LoadConfig() override;
    /// \brief Nothing to initialise.
    void Initialize() override {}

    /// \brief Sets the medium (name, pressure, temperature) and loads its tables from its medium file,
    /// opened by the medium (nullptr: no tables)
    void SetMedium(const TRestDetectorMedium& medium, TFile* file);

    /// \brief Mean energy to create an ionisation electron (REST energy units).
    inline double GetWValue() const { return fWValue; }
    /// \brief Fano factor.
    inline double GetFanoFactor() const { return fFanoFactor; }
    /// \brief Drift field in V/mm (0 if not given)
    inline double GetDriftField() const { return fDriftField; }

    /// \brief Whether there are transport tables (otherwise the fixed parameters are used)
    inline bool HasTransportTables() const { return !fTransportTables.empty(); }
    /// \brief Transport table for a field (V/mm), nullptr without tables (see class description)
    const TRestDetectorTransportTable* GetTransportTable(double field) const;

    /// Parameters of a carrier at a field (V/mm) and the pressure of the medium. Without tables, the fixed
    /// ones (only electrons, Townsend 0). Throw if the carrier is not available
    double GetDriftVelocity(double field, const std::string& carrier = "electron") const;
    /// \brief Longitudinal diffusion (sqrt(cm)) of a carrier at a field (V/mm).
    double GetLongitudinalDiffusion(double field, const std::string& carrier = "electron") const;
    /// \brief Transversal diffusion (sqrt(cm)) of a carrier at a field (V/mm).
    double GetTransversalDiffusion(double field, const std::string& carrier = "electron") const;
    /// \brief Townsend coefficient (1/cm) of a carrier at a field (V/mm); 0 without tables.
    double GetTownsend(double field, const std::string& carrier = "electron") const;
    /// \brief Attachment coefficient (1/cm) of a carrier at a field (V/mm).
    double GetAttachment(double field, const std::string& carrier = "electron") const;
    /// Electron parameters at the drift field (driftField; without transport tables, the fixed ones).
    /// Throw if there are transport tables and no driftField
    double GetDriftVelocity() const;
    /// \brief Electron longitudinal diffusion (sqrt(cm)) at the drift field.
    double GetLongitudinalDiffusion() const;
    /// \brief Electron transversal diffusion (sqrt(cm)) at the drift field.
    double GetTransversalDiffusion() const;
    /// \brief Electron attachment coefficient (1/cm) at the drift field.
    double GetAttachment() const;

    /// \brief Gain table of a gap (mm) at the pressure and temperature of the medium, with the key if not
    /// empty. Throws if there is none, or several and no key.
    const TRestDetectorGainTable& GetGainTable(double gap, const std::string& key = "") const;

    /// \brief Drifts one electron created at position, at distance (> 0, mm) from the readout along normal
    /// (unit vector pointing to the cathode): gaussian diffusion (sigma = D * sqrt(distance), D in
    /// sqrt(cm)) and attachment (1/cm), the coefficients at the field (GetLongitudinalDiffusion...).
    /// \return false if the electron is attached. Otherwise position is the diffused position.
    static bool DiffuseElectron(ROOT::Math::XYZVector& position, const ROOT::Math::XYZVector& normal,
                                double distance, double longDiff, double transDiff, double attachment,
                                TRandom& random);
};

/// \class TRestDetectorScintillationComponent
/// \brief One component of a scintillation time profile (TRestDetectorScintillationProfile): the fraction of
/// the photons emitted with it, and its rise and decay times. The emission time of a photon of the
/// component is Exp(decayTime) + Exp(riseTime), whose distribution is the usual pulse
/// (exp(-t / decayTime) - exp(-t / riseTime)) / (decayTime - riseTime) (exp(-t / decayTime) / decayTime
/// without rise time).
///
/// Parameters: fraction (1), riseTime (0), decayTime (0: emitted at once).
class TRestDetectorScintillationComponent : public TRestMetadata {
   public:
    /// `fraction`: fraction of the photons of the profile emitted with this component, in (0, 1]
    double fFraction = 1;
    /// `riseTime`: rise time (0: none)
    TRestWithUnits fRiseTime = 0;  // us
    /// `decayTime`: decay time (0: no delay)
    TRestWithUnits fDecayTime = 0;  // us

    /// \brief Builds a component emitting all the photons at once.
    TRestDetectorScintillationComponent();
    /// \brief Builds the component from one entry of `components` (LoadConfig).
    TRestDetectorScintillationComponent(const std::string& instanceName, const YAML::Node& node);

    /// \brief Returns the class name, "TRestDetectorScintillationComponent".
    std::string GetClassName() const override { return "TRestDetectorScintillationComponent"; }
    /// \brief Reads the parameters; throws if the fraction is not in (0, 1] or a time is negative.
    void LoadConfig() override;
    /// \brief Nothing to initialise.
    void Initialize() override {}
};

/// \class TRestDetectorScintillationProfile
/// \brief Time profile of the scintillation of some particles: its components
/// (TRestDetectorScintillationComponent, fractions adding up to 1) and the particles it applies to
/// (REST_Particles names: e-, alpha, Ar40..., or "ion" for any nucleus; none: the default profile, for the
/// other particles and the hits without particle, e.g. data). One entry of the `scintillation` list of a
/// TRestDetectorLightResponse.
class TRestDetectorScintillationProfile : public TRestMetadata {
   public:
    /// `particles`: names of the particles of the profile (empty: default profile)
    std::vector<std::string> fParticles;
    /// `components`: the components of the profile
    std::vector<TRestDetectorScintillationComponent> fComponents;

    /// \brief Builds an empty profile.
    TRestDetectorScintillationProfile();
    /// \brief Builds the profile from one entry of `scintillation` (LoadConfig).
    TRestDetectorScintillationProfile(const std::string& instanceName, const YAML::Node& node);

    /// \brief Returns the class name, "TRestDetectorScintillationProfile".
    std::string GetClassName() const override { return "TRestDetectorScintillationProfile"; }
    /// \brief Reads the parameters; throws if there are no components, their fractions do not add up to 1 or
    /// a particle is not known.
    void LoadConfig() override;
    /// \brief Nothing to initialise.
    void Initialize() override {}

    /// \brief Whether it is the default profile (no particles).
    inline bool IsDefault() const { return fParticles.empty(); }
    /// \brief Whether the profile applies to a particle (Particle ID, PDG encoding; REST_Particles::Matches).
    bool AppliesTo(int particleID) const;
    /// \brief Samples the emission time of a photon (us): a component by its fraction, then its time.
    double SampleTime(TRandom& random) const;
};

/// \class TRestDetectorLightResponse
/// \brief Light response of a scintillating medium: the light produced by the energy deposits (used by
/// TRestDetectorScintillationProcess) and its propagation to the photocathode in a transparent scintillator
/// (attenuation model of TRestDetectorLightCollectionProcess). It is the `light` key of a TRestDetectorMedium
/// (no class key). The quenching is done on the Geant4 deposits (TRestGeant4QuenchingProcess); the local
/// capture of an opaque scintillator and the quantum efficiency are parameters of
/// TRestDetectorLightCollectionProcess.
///
/// Parameters:
/// - lightYield: scintillation photons produced per keV of (quenched) deposited energy.
/// - attenuationLength: the deposited energy reaching the readout is E exp(-d / attenuationLength), with d
///   the distance to the readout of the channel (TRestDetectorReadout::GetDistanceToReadout).
/// - effectiveLightSpeed: the signal is delayed by d / effectiveLightSpeed (effective speed along the
///   scintillator, with its reflections).
/// - scintillation: time profiles of the emission of the photons (TRestDetectorScintillationProfile), per
///   particle (Particle ID of the hits, TRestDetectorHitsEvent::GetParticleID), e.g. for pulse shape
///   discrimination; at most one without particles (the default). A particle without profile (and without
///   default) is emitted at once.
///
///      light:
///        lightYield: 10
///        attenuationLength: 3 m
///        effectiveLightSpeed: 150 mm/ns
///        scintillation:
///          - components:                        # default
///              - {fraction: 0.8, riseTime: 0.9 ns, decayTime: 2.1 ns}
///              - {fraction: 0.2, decayTime: 20 ns}
///          - particles: ["alpha", "proton", "ion"]
///            components:
///              - {fraction: 0.5, decayTime: 2.1 ns}
///              - {fraction: 0.5, decayTime: 60 ns}
class TRestDetectorLightResponse : public TRestMetadata {
   public:
    /// `lightYield`: scintillation photons per keV (0: not given)
    double fLightYield = 0;  // 1/keV
    /// `attenuationLength`: attenuation length of the light (0: none)
    TRestWithUnits fAttenuationLength = 0;  // mm
    /// `effectiveLightSpeed`: effective speed of the light to the readout (0: no delay)
    TRestWithUnits fEffectiveLightSpeed = 0;  // mm/us
    /// `scintillation`: time profiles of the scintillation (empty: photons emitted at once)
    std::vector<TRestDetectorScintillationProfile> fScintillation;

    /// \brief Builds an empty light response.
    TRestDetectorLightResponse();
    /// \brief Builds the response from the `light` node of a medium (LoadConfig).
    TRestDetectorLightResponse(const std::string& instanceName, const YAML::Node& node);

    /// \brief Returns the class name, "TRestDetectorLightResponse".
    std::string GetClassName() const override { return "TRestDetectorLightResponse"; }
    /// \brief Reads the parameters; throws if one of them is negative or there is more than one default
    /// scintillation profile.
    void LoadConfig() override;
    /// \brief Nothing to initialise.
    void Initialize() override {}

    /// \brief Scintillation photons per keV.
    inline double GetLightYield() const { return fLightYield; }
    /// \brief Attenuation length (mm).
    inline double GetAttenuationLength() const { return fAttenuationLength; }
    /// \brief Effective light speed (mm/us).
    inline double GetEffectiveLightSpeed() const { return fEffectiveLightSpeed; }
    /// \brief Scintillation profile of a particle (Particle ID): the first one applying to it, otherwise the
    /// default one; nullptr if none.
    const TRestDetectorScintillationProfile* GetScintillationProfile(int particleID) const;
    /// \brief Samples the emission time (us) of a photon of a particle with its profile; 0 without profile.
    double GetScintillationTime(int particleID, TRandom& random) const;
};

/// \class TRestDetectorWLSResponse
/// \brief Wavelength shifting response of a medium (e.g. a WLS fibre, bar or plate): the light it absorbs is
/// re-emitted after a delay and guided to its readout, attenuated and delayed with the distance. It is the
/// `wls` key of a TRestDetectorMedium (no class key).
///
/// Parameters:
/// - attenuationLength: the photons reaching the readout are a fraction exp(-d / attenuationLength) of
///   those guided, d the distance along the medium to the readout (0: no attenuation).
/// - lightSpeed: speed of the guided light along the medium, the delay is d / lightSpeed (0: no delay).
/// - decayTime: decay time of the re-emission, each photon is delayed by Exp(decayTime) (0: no delay).
/// - endReflectivity: fraction of the light reflected at an end not read (e.g. a mirrored fibre end read
///   at the other one, TRestDetectorReadout::GetGuidedLightPaths), 0 (default) to 1.
///
///      wls:
///        attenuationLength: 3.5 m
///        lightSpeed: 170 mm/ns
///        decayTime: 8 ns
///        endReflectivity: 0.8
class TRestDetectorWLSResponse : public TRestMetadata {
   public:
    /// `attenuationLength`: attenuation length along the medium (0: none)
    TRestWithUnits fAttenuationLength = 0;  // mm
    /// `lightSpeed`: speed of the guided light along the medium (0: no delay)
    TRestWithUnits fLightSpeed = 0;  // mm/us
    /// `decayTime`: decay time of the re-emission (0: no delay)
    TRestWithUnits fDecayTime = 0;  // us
    /// `endReflectivity`: fraction of the light reflected at an end not read (0 to 1)
    double fEndReflectivity = 0;

    /// \brief Builds an empty response.
    TRestDetectorWLSResponse();
    /// \brief Builds the response from the `wls` node of a medium (LoadConfig).
    TRestDetectorWLSResponse(const std::string& instanceName, const YAML::Node& node);

    /// \brief Returns the class name, "TRestDetectorWLSResponse".
    std::string GetClassName() const override { return "TRestDetectorWLSResponse"; }
    /// \brief Reads the parameters; throws if one of them is negative.
    void LoadConfig() override;
    /// \brief Nothing to initialise.
    void Initialize() override {}

    /// \brief Attenuation length along the medium (mm).
    inline double GetAttenuationLength() const { return fAttenuationLength; }
    /// \brief Speed of the guided light (mm/us).
    inline double GetLightSpeed() const { return fLightSpeed; }
    /// \brief Decay time of the re-emission (us).
    inline double GetDecayTime() const { return fDecayTime; }
    /// \brief Fraction of the light reflected at an end not read.
    inline double GetEndReflectivity() const { return fEndReflectivity; }
    /// \brief Samples the re-emission delay of a photon (us): Exp(decayTime), 0 without decay time.
    double GetReemissionTime(TRandom& random) const;
};

/// \class TRestDetectorMedium
/// \brief A material (gas, liquid or solid) at its conditions, with its medium file (the tables generated
/// by restGarfield, read without Garfield++) and its responses. It describes the material, not the detector
/// technology: what is measured in it is given by the readout and the responses.
///
/// The same section is used by restGarfield (the `medium` of a TRestDetectorTransportManager: it writes
/// its tables to mediumFile, components needed) and by the processes (a metadata of the
/// TRestManager, found by name with their `medium` field). It is self-contained: LoadConfig reads the
/// medium file, if it exists, and gives it with the conditions to its responses.
///
/// Parameters:
/// - name: the name of the medium in its file (default: the name of the section, as any metadata).
/// - state: gas, liquid or solid.
/// - components: names and molar fractions in percent (for gases, volume fractions or partial
///   pressures), e.g. {Ar: 99, iC4H10: 1} or {Si: 100}. Read from the medium file if not given; if given,
///   they must agree with it.
/// - mediumFile: path of the medium file (a leading ~ is $HOME). restGarfield writes to it (by default
///   `<name>.root`). It can be a URL for reading (downloaded and cached, TRestTools::GetLocalFile; e.g. a
///   versioned table of rest-common); a URL that cannot be downloaded is an error.
/// - pressure (gases only, 1 bar), temperature (293.15 K): the conditions of the detector (and the default
///   ones of the tables of restGarfield). A pressure other than 1 bar for a liquid or a solid is an error
///   (1 bar is accepted, it is written to the metadata for any state).
/// - Responses, each one a key without class: `charge` (TRestDetectorChargeResponse: ionisation, transport
///   and gain), `light` (TRestDetectorLightResponse: production and propagation of the scintillation light)
///   and `wls` (TRestDetectorWLSResponse: wavelength shifting, re-emission and guiding of the light).
///
///    medium:
///      class: "TRestDetectorMedium"
///      name: "ArIso"
///      mediumFile: "~/.rest/media/ArIso.root"
///      pressure: 1.4 bar
///      charge:
///        wValue: 26.2 eV
///        fanoFactor: 0.2
///        driftField: 140 V/cm
///
/// \author JuanAn García <juanangp@unizar.es>
class TRestDetectorMedium : public TRestMetadata {
   private:
    std::shared_ptr<TRestDetectorChargeResponse> fCharge;  //!
    std::shared_ptr<TRestDetectorLightResponse> fLight;    //!
    std::shared_ptr<TRestDetectorWLSResponse> fWLS;        //!

   public:
    /// Values accepted by `state`
    inline static const std::vector<std::string> kStates = {"gas", "liquid", "solid"};
    std::string fState = "gas";                 ///< `state`: gas, liquid or solid
    std::map<std::string, double> fComponents;  ///< `components`: name and molar fraction (%) of each one
    std::string fMediumFile = "";               ///< `mediumFile`: path of the medium file
    TRestWithUnits fPressure = 1;               ///< `pressure` (bar)
    double fTemperature = 293.15;               ///< `temperature` (K)
    /// Configuration of the charge response (`charge` key)
    YAML::Node fChargeNode;
    /// Configuration of the light response (`light` key)
    YAML::Node fLightNode;
    /// Configuration of the wavelength shifting response (`wls` key)
    YAML::Node fWLSNode;

    /// \brief Builds an empty medium.
    TRestDetectorMedium();
    /// \brief Builds the medium from an in-memory YAML section (LoadConfig).
    TRestDetectorMedium(const std::string& instanceName, const YAML::Node& node);
    /// \brief Builds the medium from the section sectionName of a YAML file (LoadConfig).
    TRestDetectorMedium(const std::string& fileName, const std::string& sectionName);
    ~TRestDetectorMedium() override;

    /// \brief Returns the class name, "TRestDetectorMedium".
    std::string GetClassName() const override { return "TRestDetectorMedium"; }
    /// \brief Reads the parameters, reads the definition of the medium from its file
    /// if it exists (checking the components), checks the pressure of non gases and creates the responses
    /// with the medium file and conditions.
    void LoadConfig() override;
    /// \brief Nothing to initialise.
    void Initialize() override {}

    /// \brief Whether the state is gas.
    inline bool IsGas() const { return fState == "gas"; }
    /// \brief Pressure (bar).
    inline double GetPressure() const { return fPressure; }
    /// \brief Temperature (K).
    inline double GetTemperature() const { return fTemperature; }

    /// \brief Charge response, nullptr if the medium has no `charge`
    inline const TRestDetectorChargeResponse* GetChargeResponse() const { return fCharge.get(); }
    /// \brief Charge response; throws if the medium has no `charge` (user is for the message)
    const TRestDetectorChargeResponse& GetChargeResponse(const std::string& user) const;

    /// \brief Light response, nullptr if the medium has no `light`
    inline const TRestDetectorLightResponse* GetLightResponse() const { return fLight.get(); }
    /// \brief Light response; throws if the medium has no `light` (user is for the message)
    const TRestDetectorLightResponse& GetLightResponse(const std::string& user) const;

    /// \brief Wavelength shifting response, nullptr if the medium has no `wls`
    inline const TRestDetectorWLSResponse* GetWLSResponse() const { return fWLS.get(); }
    /// \brief Wavelength shifting response; throws if the medium has no `wls` (user is for the message)
    const TRestDetectorWLSResponse& GetWLSResponse(const std::string& user) const;

    /// \brief Whether the medium has the response of that key: "charge", "light" or "wls".
    bool HasResponse(const std::string& response) const;

    /// \brief The medium a process uses for a response ("charge", "light" or "wls"): the medium name of the
    /// manager, which must have that response, or, if name is empty, the only medium with that response
    /// (nullptr if there is none). Throws if name is not found, if it has not the response or if name is
    /// empty and several media have it. user (the process) and field (its field with the name) are for the
    /// messages.
    static const TRestDetectorMedium* Find(const TRestManager& manager, const std::string& name,
                                           const std::string& response, const std::string& user,
                                           const std::string& field = "medium");

    /// \brief YAML of the medium stored in its file (name, state, components)
    YAML::Node GetDefinition() const;
    /// \brief Path of the medium file: mediumFile (~ expanded) or `<name>.root`
    std::filesystem::path GetMediumFile() const;
    /// \brief Metadata of the medium name in a medium file to update: the stored one, or definition if the
    /// file has none. Throws if the components of definition and of the file differ.
    static YAML::Node GetFileMetadata(TFile* file, const std::string& name, const YAML::Node& definition);
};

