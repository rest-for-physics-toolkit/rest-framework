#ifndef TRESTDETECTORAVALANCHEPROCESS_H
#define TRESTDETECTORAVALANCHEPROCESS_H

#include <memory>
#include <string>

#include "TRandom3.h"
#include "TRestDetectorAmplificationResponse.h"
#include "TRestDetectorReadout.h"
#include "TRestEventProcess.h"

class TRestDetectorChargeResponse;

/// \class TRestDetectorAvalancheProcess
/// \brief Multiplies the drifted electrons of a TRestDetectorHitsEvent by the avalanche gain of the
/// amplification gap, from a gain table of the TRestDetectorMedium (TRestDetectorGainTable, uniform field) or
/// from an amplification response in the field map of a unit cell (TRestDetectorAmplificationResponse,
/// `responseFile`: transparency, avalanche size and time), both generated by restGarfield.
///
/// The parameters (YAML keys), the observables and an example are described in the class documentation
/// (TRestDetectorAvalancheProcess.cxx).
///
/// \author Javier G. Garza
/// \author JuanAn García <juanangp@unizar.es>
class TRestDetectorAvalancheProcess : public TRestEventProcess {
   private:
    const TRestDetectorChargeResponse* fCharge = nullptr;
    std::shared_ptr<const TRestDetectorAmplificationResponse> fResponse;  //!
    /// Readout locating the hits in the pixels (map of the cell) and giving the plane of the charge sharing
    const TRestDetectorReadout* fReadout = nullptr;  //!
    /// The size of the cell of the response and of the pixels has been compared (once)
    bool fCellChecked = false;  //!
    /// A hit without readout normal (no charge sharing) has been reported (once)
    bool fNormalWarned = false;  //!
    TRandom3 fRandom;            //!

    /// \brief Warns once if the cell of the response and the pixel of the readout differ by more than 5 %
    void CheckCell(const TRestDetectorReadout::PixelPosition& pixel);
    /// \brief A position moved in the plane of the readout by a Gaussian of sigma fSharingSigma along each
    /// axis of the plane (the position itself, with a warning once, where the readout has no normal)
    ROOT::Math::XYZVector Share(const ROOT::Math::XYZVector& position);

   public:
    /// Voltage across the amplification gap
    TRestWithUnits fAmplificationVoltage = 0;  // V
    /// Amplification gap (uniform field amplificationVoltage / gap)
    TRestWithUnits fGap = 0;  // mm
    /// Name of the TRestDetectorMedium (with `charge`). Empty: the only medium with `charge`.
    std::string fMediumName = "";
    /// Key of the amplification table. Only needed if the medium has several with the gap
    std::string fTable = "";
    /// `responseFile`: file of an amplification response in a field map (restGarfield, `amplification` key of
    /// TRestDetectorTransportManager), instead of amplificationVoltage and gap (the gain table)
    std::string fResponseFile = "";
    /// `readout`: name of the readout (in TRestDetectorReadoutManager) locating the hits in its pixels, used
    /// with a response with the map of the cell. It can be omitted if the manager contains a single readout.
    std::string fReadoutName = "";
    /// Seed of the random generator (0: random seed). Otherwise the generator is re-seeded at each event
    /// with TRestEvent::EventSeed (seed, event and subevent IDs): independent of the threads.
    unsigned long fSeed = 0;

    /// Written with the values used (not inputs): mean gain and Polya parameter at the field (or of the
    /// collected avalanches of the response)
    double fGain = 0;
    /// Polya parameter theta at the field, written with the value used (not an input)
    double fTheta = 0;
    /// Transparency of the response (fraction of the electrons amplified; 1 with a gain table), written with
    /// the value used (not an input)
    double fTransparency = 1;
    /// Sigma (mm) of the displacement of the hits in the readout plane from the charge sharing of the
    /// response (TRestDetectorAmplificationResponse::GetSharingSigma; 0 with a gain table), written with the
    /// value used (not an input)
    double fSharingSigma = 0;

    /// \brief Default constructor (no configuration).
    TRestDetectorAvalancheProcess();
    /// \brief Builds the process from an in-memory YAML section (LoadConfig).
    TRestDetectorAvalancheProcess(const std::string& instanceName, const YAML::Node& node);
    /// \brief Builds the process from the section sectionName of a YAML file (LoadConfig).
    TRestDetectorAvalancheProcess(const std::string& fileName, const std::string& sectionName);

    /// \brief Reads the parameters from the YAML node.
    void LoadConfig() override;
    /// \brief Gets the charge response of the medium and either reads the amplification response of
    /// responseFile (with the readout if it has the map of the cell or charge sharing) or checks
    /// amplificationVoltage and gap and gets the gain and theta of its gain table at the field
    /// amplificationVoltage / gap (written to the metadata). Throws if one of them is missing or out of
    /// range, if both responseFile and amplificationVoltage or gap are given, or if the response has the map
    /// of the cell or charge sharing and there is no readout.
    void InitProcess() override;
    /// \brief Multiplies the energy of each hit by its avalanche gain per electron (see the class
    /// description).
    /// \return false if the event has no hits.
    bool ProcessEvent(const TRestEvent& input, TRestEvent& output) override;
    /// \brief Nothing to do at the end of the processing.
    void EndProcess() override {}

    /// \brief Input event type, "TRestDetectorHitsEvent".
    std::string GetInputEvent() const override { return "TRestDetectorHitsEvent"; }
    /// \brief Output event type, "TRestDetectorHitsEvent".
    std::string GetOutputEvent() const override { return "TRestDetectorHitsEvent"; }

    /// \brief Returns the class name, "TRestDetectorAvalancheProcess".
    std::string GetClassName() const override { return "TRestDetectorAvalancheProcess"; }
};

#endif
